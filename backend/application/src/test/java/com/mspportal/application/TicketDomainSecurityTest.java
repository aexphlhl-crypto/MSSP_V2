    // =========================================================================
    // Test 9: Internal comments inaccessible to customer role
    // =========================================================================
    @Test
    @Order(9)
    public void test9_internalComment_notVisible_toCustomer() throws Exception {
        // Platform admin adds an internal note
        AddCommentRequest internalNote = new AddCommentRequest();
        internalNote.setContent("INTERNAL: Server will be rebooted at 2AM");
        internalNote.setInternal(true);

        MvcResult result = mockMvc.perform(post("/api/v1/tickets/" + tenantATicketId + "/comments")
                        .header("Authorization", "Bearer " + platformAdminToken)
                        .param("tenantId", TENANT_A)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(internalNote)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.internal").value(true)).andReturn();

        // Customer (tenant A) requests comments — should NOT see the internal note
        MvcResult customerResult = mockMvc.perform(get("/api/v1/tickets/" + tenantATicketId + "/comments")
                        .header("Authorization", "Bearer " + tenantAToken))
                .andExpect(status().isOk())
                .andReturn();

        String commentsJson = customerResult.getResponse().getContentAsString();
        // The customer's response should be an empty array or only contain non-internal comments
        // If INTERNAL_NOTE_ADDED comment was returned, this test fails
        assertThat(commentsJson).doesNotContain("INTERNAL: Server will be rebooted");
    }


    // Test 1: Tenant A can create, read, and update its own tickets
    // =========================================================================
    @Test
    @Order(1)
    public void test1_tenantA_canCreateAndReadOwnTicket() throws Exception {
        Map<String, Object> body = Map.of(
                "title", "Test Ticket from Tenant A",
                "description", "Description text",
                "priority", "HIGH",
                "category", "NETWORK"
        );

        MvcResult createResult = mockMvc.perform(post("/api/v1/tickets")
                        .header("Authorization", "Bearer " + tenantAToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(body)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.title").value("Test Ticket from Tenant A"))
                .andExpect(jsonPath("$.status").value("OPEN"))
                .andExpect(jsonPath("$.tenantId").value(TENANT_A))
                .andReturn();

        String ticketId = objectMapper.readTree(createResult.getResponse().getContentAsString())
                .get("id").asText();

        // Read it back
        MvcResult result = mockMvc.perform(get("/api/v1/tickets/" + ticketId)
                        .header("Authorization", "Bearer " + tenantAToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(ticketId))
                .andReturn();
    }


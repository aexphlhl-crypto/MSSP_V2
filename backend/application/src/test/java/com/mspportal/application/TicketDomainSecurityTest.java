    // Test 10: Public comments visible to authorized roles
    // =========================================================================
    @Test
    @Order(10)
    public void test10_publicComment_visible_toCustomer() throws Exception {
        // Platform admin adds a public reply
        AddCommentRequest publicReply = new AddCommentRequest();
        publicReply.setContent("We are investigating the issue.");
        publicReply.setInternal(false);

        MvcResult result = mockMvc.perform(post("/api/v1/tickets/" + tenantATicketId + "/comments")
                        .header("Authorization", "Bearer " + platformAdminToken)
                        .param("tenantId", TENANT_A)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(publicReply)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.internal").value(false)).andReturn();

        // Customer can see it
        MvcResult customerResult2 = mockMvc.perform(get("/api/v1/tickets/" + tenantATicketId + "/comments")
                        .header("Authorization", "Bearer " + tenantAToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[0].content").value("We are investigating the issue."))
                .andExpect(jsonPath("$[0].internal").value(false))
                .andReturn();
    }

    // =========================================================================
    // Test 11: TicketHistory generated for status change
    // =========================================================================
    @Test
    @Order(11)
    public void test11_ticketHistory_generatedFor_statusChange() throws Exception {
        UpdateTicketStatusRequest req = new UpdateTicketStatusRequest();
        req.setStatus(TicketStatus.IN_PROGRESS);
        MvcResult result = mockMvc.perform(patch("/api/v1/tickets/" + tenantATicketId + "/status")
                        .header("Authorization", "Bearer " + tenantAToken)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(req)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("IN_PROGRESS")).andReturn();

        // Verify history record was persisted
        MvcResult historyResult = mockMvc.perform(get("/api/v1/tickets/" + tenantATicketId + "/history")
                        .header("Authorization", "Bearer " + tenantAToken))
                .andExpect(status().isOk())
                .andReturn();

        String historyJson = historyResult.getResponse().getContentAsString();
        assertThat(historyJson).contains("STATUS_CHANGED");
        assertThat(historyJson).contains("OPEN");
        assertThat(historyJson).contains("IN_PROGRESS");
    }

